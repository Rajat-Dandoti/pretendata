// The answer key for a dataset: what was generated, how to regenerate it, and what a detector
// should do with each column. Everything a scorer needs, and nothing it has to be told separately.
import { AVAILABLE_COLUMNS, ColumnDef, Expectation, PrivacyCategory, ValidationKind, expectationFor } from '../data/schema';
import { frameworksFor, ColumnFrameworks } from './frameworks';
import { GENERATOR_VERSION, STREAM_CHUNK_ROWS, HeaderMode, generateChunkRows, generateRows, headersFor } from './generate';
import type { LocaleId } from './locale';
import { patternFor } from './reference';

export const MANIFEST_VERSION = 2;

/** How rows were seeded: one stream for in-memory runs, one seed per chunk for streamed files. */
export type Seeding = 'whole' | 'chunked';

export interface RunMeta {
  seed: number | null;
  rowCount: number;
  sparsityPct: number;
  locale: LocaleId;
  seeding: Seeding;
  /** Share of rows (1–100) in which a should-fire column holds the real value. */
  densityPct: number;
  headerMode: HeaderMode;
}

export interface ManifestColumn {
  id: string;
  name: string;
  /** The header this column carries in a CSV file. */
  header: string;
  /** The key this column carries in flat JSON and NDJSON. */
  key: string;
  category: PrivacyCategory;
  region?: string;
  validation: ValidationKind;
  expectation: Expectation;
  /** Regex the values match, where the column has a fixed shape. */
  pattern?: string;
  /** For near-miss columns: the id of the valid column this one imitates. */
  nearMissOf?: string;
  /** Per-regulation classification (GDPR, HIPAA, DPDPA, …). 'none' entries are omitted. */
  frameworks: ColumnFrameworks;
}

export interface Manifest extends RunMeta {
  version: number;
  generatedAt: string;
  toolName: string;
  /** Seed contract the data was generated under; a different value will not reproduce it. */
  generatorVersion: number;
  /** Rows per independently seeded chunk, when seeding is 'chunked'. */
  chunkRows?: number;
  columns: ManifestColumn[];
}

function toManifestColumn(c: ColumnDef, header: string, key: string): ManifestColumn {
  const validation = c.validation ?? 'free-form';
  return {
    id: c.id,
    name: c.name,
    header,
    key,
    category: c.category,
    region: c.region,
    validation,
    expectation: expectationFor(c),
    pattern: patternFor(c.id),
    nearMissOf: validation.startsWith('near-miss-of:') ? validation.slice('near-miss-of:'.length) : undefined,
    frameworks: frameworksFor(c),
  };
}

export function buildManifest(selectedColumnIds: Iterable<string>, meta: RunMeta): Manifest {
  const ids = new Set(selectedColumnIds);
  const cols = AVAILABLE_COLUMNS.filter(c => ids.has(c.id));
  const headers = headersFor(cols, meta.headerMode, 'name'), keys = headersFor(cols, meta.headerMode, 'id');
  return {
    version: MANIFEST_VERSION,
    generatedAt: new Date().toISOString(),
    toolName: 'pretendata',
    generatorVersion: GENERATOR_VERSION,
    ...meta,
    chunkRows: meta.seeding === 'chunked' ? STREAM_CHUNK_ROWS : undefined,
    columns: cols.map((c, i) => toManifestColumn(c, headers[i], keys[i])),
  };
}

/** Rebuild the exact rows a manifest describes. Only seeded runs can be rebuilt. */
export function rowsFromManifest(m: Manifest): Record<string, any>[] {
  if (m.seed === null) throw new Error('This dataset was generated without a seed, so it cannot be regenerated.');
  if (m.generatorVersion !== GENERATOR_VERSION) {
    throw new Error(`This dataset was generated by generator version ${m.generatorVersion}; this build is version ${GENERATOR_VERSION} and would produce different values.`);
  }
  const columnIds = m.columns.map(c => c.id);
  if (m.seeding === 'whole') {
    return generateRows({ columnIds, rowCount: m.rowCount, sparsity: m.sparsityPct, seed: m.seed, locale: m.locale, density: m.densityPct });
  }
  const cols = AVAILABLE_COLUMNS.filter(c => columnIds.includes(c.id));
  const size = m.chunkRows ?? STREAM_CHUNK_ROWS;
  const out: Record<string, any>[] = [];
  for (let chunk = 0; chunk * size < m.rowCount; chunk++) {
    const rows = Math.min(size, m.rowCount - chunk * size);
    out.push(...generateChunkRows(cols, { seed: m.seed, chunk, rows, sparsity: m.sparsityPct, locale: m.locale, density: m.densityPct }));
  }
  return out;
}

// ---------- self-check (run via `npm test`) ----------
export function _selfCheck() {
  const meta: RunMeta = { seed: 1, rowCount: 10, sparsityPct: 20, locale: 'en_IN', seeding: 'whole', densityPct: 100, headerMode: 'descriptive' };
  const m = buildManifest(['aadhaar', 'email', 'aadhaar_invalid', 'createdAt'], meta);
  const col = (id: string) => m.columns.find(c => c.id === id)!;
  if (col('aadhaar').validation !== 'verhoeff' || col('aadhaar').region !== 'IN' || col('aadhaar').expectation !== 'detect') {
    throw new Error('FAIL: manifest aadhaar metadata');
  }
  if (col('aadhaar_invalid').nearMissOf !== 'aadhaar' || col('aadhaar_invalid').expectation !== 'ignore') throw new Error('FAIL: manifest near-miss metadata');
  if (col('aadhaar').pattern !== '\\d{12}' || col('aadhaar').header !== 'Aadhaar (IN)' || col('aadhaar').key !== 'aadhaar') throw new Error('FAIL: manifest pattern/header');
  // the key records what the file calls each column, whatever the header mode
  const neutral = buildManifest(['aadhaar', 'email'], { ...meta, headerMode: 'neutral' }).columns;
  const swapped = buildManifest(['aadhaar', 'email'], { ...meta, headerMode: 'misleading' }).columns;
  if (neutral.map(c => c.header + c.key).join() !== 'col_01col_01,col_02col_02') throw new Error('FAIL: manifest neutral headers');
  if (swapped.find(c => c.id === 'aadhaar')!.header !== 'Email Address' || swapped.find(c => c.id === 'aadhaar')!.key !== 'email') throw new Error('FAIL: manifest misleading headers');

  // every column has an expectation; controls are never expected to fire
  for (const c of AVAILABLE_COLUMNS) {
    const e = expectationFor(c);
    if (!e) throw new Error(`FAIL: no expectation for ${c.id}`);
    if ((c.category === 'DLP-Negative' || c.category === 'Chaos') && e !== 'ignore') throw new Error(`FAIL: control column ${c.id} must be 'ignore'`);
  }

  // a manifest alone is enough to rebuild the data — after a JSON round-trip, as a real file would be
  const ids = m.columns.map(c => c.id);
  const fromFile = (x: Manifest): Manifest => JSON.parse(JSON.stringify(x));
  const whole = generateRows({ columnIds: ids, rowCount: 10, sparsity: 20, seed: 1, locale: 'en_IN' });
  if (JSON.stringify(rowsFromManifest(fromFile(m))) !== JSON.stringify(whole)) throw new Error('FAIL: rowsFromManifest (whole)');
  const big = buildManifest(ids, { ...meta, rowCount: STREAM_CHUNK_ROWS + 7, seeding: 'chunked' });
  const cols = AVAILABLE_COLUMNS.filter(c => ids.includes(c.id));
  const expected = [0, 1].flatMap(chunk => generateChunkRows(cols, { seed: 1, chunk, rows: chunk ? 7 : STREAM_CHUNK_ROWS, sparsity: 20, locale: 'en_IN' }));
  if (JSON.stringify(rowsFromManifest(fromFile(big))) !== JSON.stringify(expected)) throw new Error('FAIL: rowsFromManifest (chunked)');
  // thinned-out data rebuilds too
  const thin = buildManifest(ids, { ...meta, densityPct: 30 });
  if (JSON.stringify(rowsFromManifest(fromFile(thin))) !== JSON.stringify(generateRows({ columnIds: ids, rowCount: 10, sparsity: 20, seed: 1, locale: 'en_IN', density: 30 }))) throw new Error('FAIL: rowsFromManifest (density)');
  let refused = false;
  try { rowsFromManifest({ ...m, generatorVersion: GENERATOR_VERSION + 1 }); } catch { refused = true; }
  if (!refused) throw new Error('FAIL: a manifest from another generator version must be refused');
  console.log('manifest: all self-checks passed');
}

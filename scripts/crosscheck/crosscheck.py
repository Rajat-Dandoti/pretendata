"""Cross-checks Pretendata's generated identifiers against independent validators.

Reads rows as JSON (argv[1]) and prints VALIDATION.md to stdout. Witnesses:
python-stdnum for most identifiers, schwifty for the national check digits inside IBANs.
Run it through `npm run crosscheck`, which builds the environment and the input.
"""
import importlib
import json
import sys
from importlib.metadata import version

import schwifty

rows = json.load(open(sys.argv[1]))

# Pretendata column -> python-stdnum module that validates it.
STDNUM = {
    'ssn': 'us.ssn', 'usItin': 'us.itin', 'routingNumber': 'us.rtn', 'aadhaar': 'in_.aadhaar', 'pan': 'in_.pan',
    'gstin': 'in_.gstin', 'voterId': 'in_.epic', 'creditCard': 'luhn', 'iban': 'iban', 'nhsNumber': 'gb.nhs',
    'imei': 'imei', 'ean13': 'ean', 'isin': 'isin', 'canadaSin': 'ca.sin', 'brazilCpf': 'br.cpf',
    'brazilCnpj': 'br.cnpj', 'spainDni': 'es.dni', 'spainNie': 'es.nie', 'netherlandsBsn': 'nl.bsn',
    'franceNir': 'fr.nir', 'australiaTfn': 'au.tfn', 'chinaResidentId': 'cn.ric', 'southAfricaId': 'za.idnr',
}
# Validated columns no witness covers yet.
UNWITNESSED = ['npi', 'dea', 'vin', 'iqama', 'ukNino', 'singaporeNric', 'uaeEmiratesId']
# Disagreements that are the witness's, with the reason.
KNOWN = {
    'usItin': 'python-stdnum accepts groups 70-99 only. The IRS has also issued groups 50-65 since 2011, which Pretendata generates.',
}


def stdnum_ok(module, value):
    mod = importlib.import_module('stdnum.' + module)
    return mod.is_valid(value.replace('-', '').replace(' ', '') if module == 'luhn' else value)


def national_ok(iban):
    """schwifty checks the check digits inside the BBAN (Spain, France, Italy, ...)."""
    try:
        schwifty.IBAN(iban, validate_bban=True)
        return True
    except schwifty.exceptions.InvalidBBANChecksum:
        return False
    except schwifty.exceptions.SchwiftyException:
        return True  # e.g. a bank code not in its registry: random bank codes are expected


n = len(rows)
out = ['# Validation against independent libraries', '',
       f'Generated by `npm run crosscheck`: {n:,} values per column, seed 77, checked with python-stdnum {version("python-stdnum")} '
       f'and schwifty {version("schwifty")}. Neither shares code with Pretendata.', '',
       '## Valid identifiers', '', 'Every value should be accepted.', '',
       '| Column | Witness | Accepted | Note |', '|---|---|---|---|']
failed = []
for col, module in STDNUM.items():
    ok = sum(stdnum_ok(module, r[col]) for r in rows)
    note = KNOWN.get(col, '')
    if ok != n and not note:
        failed.append(col)
        note = '**Unexplained disagreement**'
    out.append(f'| `{col}` | python-stdnum `{module}` | {ok:,} of {n:,} | {note} |')
ok = sum(national_ok(r['iban']) for r in rows)
if ok != n:
    failed.append('iban (national check digits)')
out.append(f'| `iban` | schwifty, national check digits | {ok:,} of {n:,} | Spain, France and Italy carry check digits inside the account number |')

out += ['', '## Negative controls', '', 'No value should be accepted as the identifier it imitates.', '',
        '| Column | Imitates | Accepted |', '|---|---|---|']
for col in sorted(rows[0]):
    origin = next((o for o in STDNUM if col in (o + '_invalid', o + '_prefix', o + '_transposed')), None)
    if not origin:
        continue
    ok = sum(stdnum_ok(STDNUM[origin], r[col]) for r in rows)
    if ok:
        failed.append(col)
    out.append(f'| `{col}` | `{origin}` | {ok:,} of {n:,} |')

out += ['', '## Not yet witnessed', '',
        'These have a validator and a published example in the self-tests, but no independent library checks them here: '
        + ', '.join(f'`{c}`' for c in UNWITNESSED) + '.', '']
print('\n'.join(out))
if failed:
    print('crosscheck: unexplained disagreement in ' + ', '.join(failed), file=sys.stderr)
    sys.exit(1)
